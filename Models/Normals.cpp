FLOAT3D_* avGouraudNormals_(INDEX i)
{
  return (FLOAT3D_*)(&(avGouraudNormals[i]));
}

INDEX GouraudNormal_(const FLOAT3D_* vNormal)
{
  const FLOAT3D& vNormalr = *((const FLOAT3D*)vNormal);
  INDEX i, besti;
  FLOAT p, bestp;
  // find the Gouraud normal that makes smallest dot product with given vector
  besti = 0;
  bestp = 0.0f;
  for( i=0; i<MAX_GOURAUDNORMALS; i++) {
    p = avGouraudNormals[i] % vNormalr;
    if( p>bestp) {
      bestp = p;
      besti = i;
    }
  }
  return besti;
}

void CompressNormal_HQ_(const FLOAT3D_* vNormal, UBYTE* ubH, UBYTE* ubP)
{
  const FLOAT3D& vNormalr = *((const FLOAT3D*)vNormal);
  ANGLE h, p;

  const FLOAT &x = vNormalr(1);
  const FLOAT &y = vNormalr(2);
  const FLOAT &z = vNormalr(3);

  // calculate pitch
  p = ASin(y);

  // if y is near +1 or -1
  if (y>0.99 || y<-0.99) {
    // heading is irrelevant
    h = 0;
  // otherwise
  } else {
    // calculate heading
    h = ATan2(-x, -z);
  }

  h = (h/360.0f)+0.5f;
  p = (p/360.0f)+0.5f;
  *ubH = UBYTE(h*255);
  *ubP = UBYTE(p*255);
}

void DecompressNormal_HQ_(FLOAT3D_* vNormal, UBYTE ubH, UBYTE ubP)
{
  FLOAT3D& vNormalr = *((FLOAT3D*)vNormal);
  ANGLE h = (ubH/255.0f)*360.0f-180.0f;
  ANGLE p = (ubP/255.0f)*180.0f-90.0f;

  FLOAT &x = vNormalr(1);
  FLOAT &y = vNormalr(2);
  FLOAT &z = vNormalr(3);

  x = -Sin(h)*Cos(p);
  y = Sin(p);
  z = -Cos(h)*Cos(p);
}
